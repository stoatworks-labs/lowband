/**
 * Lowband — browser demo.
 *
 * A Hi8 tape played back on a Video8 deck. Hi8 moved the luma's FM carrier up
 * (5.7–7.7 MHz against Video8's 4.2–5.4) and left the colour-under chroma
 * where it was, so a Video8 deck reads the Hi8 carrier through a channel and
 * a demodulator built for its own: the contrast comes out 5/3 too high, the
 * mismatched emphasis trails a glow after every highlight and lifts the black
 * at the clamp, bright edges throw black streaks where their overshoot leaves
 * the deck's band, and with tape noise the highlights break up first.
 *
 * Like receipt and colourunder, this plugin is **not only a shader**, and the
 * two halves of the page are not equally faithful:
 *
 *   The shaders are the plugin's. The version line, the `kCommon` block and
 *   the three bodies of `source/Shaders.cpp` (vertex, intake, display) are
 *   spliced into the generated block below by `demo/tools/sync_shaders.py`,
 *   tabs and comments included, and `assemble` below is Shaders.cpp's.
 *   `demo/tools/check_shaders.py --dump` compares every assembled stage with
 *   what the plugin compiles (`lbtest --dump-shaders`); `tools/verify.sh`
 *   runs it.
 *
 *   The CPU engine is a PORT. In the plugin the luma is a real FM signal at
 *   40.5 MHz, recorded, played back and demodulated in C++ on worker
 *   threads (Engine.cpp, Dsp.cpp, Model.cpp). `demo/engine.js`, `dsp.js` and
 *   `model.js` are a hand translation of it, float for float, and
 *   `demo/tools/check_port.sh` compares it with the plugin's own C++, run with
 *   its constructor and ProcessOpenGL cut out of Lowband.cpp and GL replaced
 *   by a recorder: bit-identical. This file's GL half (which WebGL object each
 *   name is, the read-back, the draws) only a reader and the comparison
 *   against `lbtest --pipe` in AGENTS.md check.
 *
 * ------------------------------------------------------ the frame
 *
 *   beginFrame  model.js: the settings, the clock, the video frame (every
 *               frame the page draws, as the plugin's clock sees every frame)
 *   intake      the host frame onto the standard's raster, P x N RGBA32F,
 *               and read back
 *   engine      engine.js in Web Workers (engine-worker.js), the frame's
 *               lines split between them; then the clamp and the AGC
 *   upload      the deck's picture, P x N RGBA32F
 *   display     nearest line per row, Catmull-Rom across, R'G'B', Mix
 *
 * The plugin does all five inside one ProcessOpenGL. Here the engine takes
 * longer than a frame, so the intake runs when the workers are free and the
 * display draws the LAST frame they finished, with the input that frame was
 * made from. Paused or stepped, that is exactly the frame shown.
 */


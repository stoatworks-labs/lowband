/// The plugin's defaultThreads(): the cores less one for the host, at most eight.
const workerCount = () => {
  const cores = typeof navigator !== 'undefined' && navigator.hardwareConcurrency ? navigator.hardwareConcurrency : 2;
  return Math.min(8, Math.max(1, cores - 1));
};

const deck = {
  workers: [],
  failed: false,
  busy: false,
  nextId: 1,
  job: null, // the frame in flight
  parts: [],
  pending: 0,
  done: null, // the last finished frame
  times: [], // finish times, for the rate
  inline: null, // the engine on the page's own thread, if there are no workers
};

/** Set once mountDemo returns: the kit's redraw and its state. */
let redraw = () => {};
let kitState = null;
/**
 * What the last frame handed to the workers was made of (the clock, the
 * parameters, the clip, the size). Paused, a new frame of tape starts only
 * when this changes, so showing a finished frame does not start it again.
 */
let lastKey = null;

function deckStart() {
  if (deck.workers.length || deck.failed) return;
  try {
    for (let i = 0; i < workerCount(); i += 1) {
      const w = new Worker(new URL('./engine-worker.js', import.meta.url), { type: 'module' });
      w.onmessage = (event) => deckPart(event.data);
      w.onerror = (event) => {
        // eslint-disable-next-line no-console
        console.error('engine-worker', event.message);
      };
      deck.workers.push(w);
    }
  } catch {
    // No module workers: run the engine on the page's thread, as the plugin
    // runs it in line, and let the page stall. Said under the picture.
    deck.workers = [];
    deck.failed = true;
    deck.inline = new Engine();
  }
}

function deckPart(msg) {
  const job = deck.job;
  if (!job || msg.id !== job.id) return;
  deck.parts.push(msg);
  job.workerMs = Math.max(job.workerMs, msg.ms);
  deck.pending -= 1;
  if (deck.pending > 0) return;
  deckFinish(finishFrame(deck.parts, job.N, job.P, job.settings));
}

function deckFinish(result) {
  const job = deck.job;
  const now = performance.now();
  deck.done = { ...job, lines: result.lines, depth: result.depth, gain: result.gain, ms: now - job.started, uploaded: false };
  deck.times.push(now);
  while (deck.times.length > 1 && now - deck.times[0] > 3000) deck.times.shift();
  deck.busy = false;
  deck.job = null;
  deck.parts = [];
  redraw();
}

/** Hand a frame's intake to the workers: each its rows, and the two rows before them. */
function deckRun(job) {
  deck.busy = true;
  deck.job = job;
  deck.parts = [];
  job.started = performance.now();
  job.workerMs = 0;
  const { P, N } = job;
  if (deck.failed || deck.workers.length === 0) {
    deck.inline = deck.inline ?? new Engine();
    const part = processRows(deck.inline, job.intake, 0, 0, N, N, P, job.settings, job.drops);
    job.workerMs = performance.now() - job.started;
    deckFinish(finishFrame([part], N, P, job.settings));
    return;
  }
  const n = Math.min(deck.workers.length, N);
  deck.pending = n;
  for (let w = 0; w < n; w += 1) {
    const r0 = Math.floor((N * w) / n);
    const r1 = Math.floor((N * (w + 1)) / n);
    const base = Math.max(0, r0 - 2);
    const data = job.intake.slice(base * P * 4, r1 * P * 4);
    deck.workers[w].postMessage(
      { id: job.id, settings: job.settings, drops: job.drops, P, N, r0, r1, base, data: data.buffer },
      [data.buffer],
    );
  }
}


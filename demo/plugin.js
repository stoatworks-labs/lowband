/// What the line under the canvas reports. Filled by the renderer.
const telemetry = {
  ticked: false, seconds: 0, videoFrame: 0, settings: null, P: 0, N: 0,
  shown: null, missing: [], workers: 0, rate: 0, behind: 0,
};

/// For a driven check (AGENTS.md, "Browser demo"). `fresh()` puts the plugin
/// instance back to a newly created one; `afterRender(gl, info)` runs inside
/// the frame, after the display pass, so it can read the canvas back.
const hooks = { afterRender: null, fresh: null };

function createRenderer(gl, quad) {
  // InitGL: both stages, as Shaders.cpp assembles them.
  const vertex = assemble(VERTEX_BODY, STAGE_COMMON.VERTEX_BODY);
  const programs = {
    intake: new Program(gl, vertex, assemble(INTAKE_BODY, STAGE_COMMON.INTAKE_BODY), 'intake'),
    display: new Program(gl, vertex, assemble(DISPLAY_BODY, STAGE_COMMON.DISPLAY_BODY), 'display'),
  };

  // The plugin's buffers: the intake P x N RGBA32F, nearest; the deck's
  // picture P x N RGBA32F, nearest (every read is texelFetch).
  const intake = new PassBuffer(gl, { filter: 'nearest' });
  let linesTexture = null;
  let linesW = 0;
  let linesH = 0;
  // Not the plugin's: the input the frame in flight was made from, so the
  // display mixes the deck's picture with ITS source, not a later one.
  const held = new PassBuffer(gl, { filter: 'nearest' });
  const readFbo = gl.createFramebuffer();

  let instance = new Instance();
  hooks.fresh = () => {
    instance = new Instance();
    deck.done = null;
    deck.job = null;
    deck.busy = false;
    deck.nextId += 1;
    lastKey = null;
  };

  const parameterFloats = (params) => {
    const p = new Array(DECLARATIONS.length).fill(0);
    p[PT.RECORDING] = params.get('recording');
    p[PT.TAPE_NOISE] = params.get('tapeNoise');
    p[PT.DROPOUTS] = params.get('dropouts');
    p[PT.DECK] = params.get('deck');
    p[PT.STANDARD] = params.get('standard');
    p[PT.HEAD_CLOG] = params.get('headClog');
    p[PT.SYNC_AGC] = params.get('syncAgc');
    p[PT.MIX] = params.get('mix');
    return p.map(Math.fround);
  };

  const draw = (program, pass, textureOf) => {
    const prog = programs[program].use();
    for (const [k, v] of Object.entries(pass.ints)) prog.setInt(k, v);
    for (const [k, v] of Object.entries(pass.floats)) prog.set(k, v);
    pass.textures.forEach((name, unit) => bindTexture(gl, unit, textureOf(name)));
    gl.activeTexture(gl.TEXTURE0);
    quad.draw();
    for (let unit = pass.textures.length - 1; unit >= 0; --unit) bindTexture(gl, unit, null);
    gl.activeTexture(gl.TEXTURE0);
  };

  return {
    render({ input, params, width, height, time }) {
      const W = width;
      const H = height;
      deckStart();

      // Lowband::SetTime, then the head of ProcessOpenGL: every frame the
      // page draws is a frame the plugin's clock sees.
      instance.setTime(time);
      const frame = instance.beginFrame(parameterFloats(params), W, H);
      const { P, N, settings } = frame;
      const plan = passes(W, H, P, N, frame.mixAmount);
      gl.disable(gl.BLEND);

      // A new frame of tape when the workers are free -- and, paused, only
      // when something about the frame has changed.
      const key = JSON.stringify([time, W, H, kitState?.sourceId, params.values]);
      const playing = kitState ? kitState.playing : true;
      if (!deck.busy && (playing || key !== lastKey)) {
        lastKey = key;
        intake.ensure(P, N, gl.RGBA32F);
        intake.bind();
        draw('intake', plan[0], () => input.texture);
        const data = new Float32Array(P * N * 4);
        gl.pixelStorei(gl.PACK_ALIGNMENT, 4);
        gl.readPixels(0, 0, P, N, gl.RGBA, gl.FLOAT, data);

        // Keep the input this frame was made from, for the display's Mix.
        held.ensure(W, H, gl.RGBA8);
        gl.bindFramebuffer(gl.READ_FRAMEBUFFER, readFbo);
        gl.framebufferTexture2D(gl.READ_FRAMEBUFFER, gl.COLOR_ATTACHMENT0, gl.TEXTURE_2D, input.texture, 0);
        gl.bindFramebuffer(gl.DRAW_FRAMEBUFFER, held.fbo);
        gl.blitFramebuffer(0, 0, W, H, 0, 0, W, H, gl.COLOR_BUFFER_BIT, gl.NEAREST);
        gl.bindFramebuffer(gl.READ_FRAMEBUFFER, null);
        gl.bindFramebuffer(gl.DRAW_FRAMEBUFFER, null);

        const id = deck.nextId;
        deck.nextId += 1;
        deckRun({
          id, P, N, W, H, settings, intake: data, drops: frameDropouts(settings, N),
          seconds: frame.seconds, time,
        });
      }

      // The last finished frame of tape, uploaded once.
      const shown = deck.done;
      if (shown && !shown.uploaded) {
        if (linesTexture === null || linesW !== shown.P || linesH !== shown.N) {
          if (linesTexture !== null) gl.deleteTexture(linesTexture);
          linesTexture = gl.createTexture();
          gl.bindTexture(gl.TEXTURE_2D, linesTexture);
          gl.texImage2D(gl.TEXTURE_2D, 0, gl.RGBA32F, shown.P, shown.N, 0, gl.RGBA, gl.FLOAT, null);
          gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MIN_FILTER, gl.NEAREST);
          gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MAG_FILTER, gl.NEAREST);
          gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_WRAP_S, gl.CLAMP_TO_EDGE);
          gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_WRAP_T, gl.CLAMP_TO_EDGE);
          linesW = shown.P;
          linesH = shown.N;
        }
        gl.bindTexture(gl.TEXTURE_2D, linesTexture);
        gl.pixelStorei(gl.UNPACK_ALIGNMENT, 4);
        gl.texSubImage2D(gl.TEXTURE_2D, 0, 0, 0, shown.P, shown.N, gl.RGBA, gl.FLOAT, shown.lines);
        gl.bindTexture(gl.TEXTURE_2D, null);
        shown.uploaded = true;
      }

      // Display: the frame of tape, over the input it was made from.
      gl.bindFramebuffer(gl.FRAMEBUFFER, null);
      gl.viewport(0, 0, W, H);
      if (shown) {
        const display = passes(W, H, shown.P, shown.N, frame.mixAmount)[1];
        const source = shown.W === W && shown.H === H ? held.texture : input.texture;
        draw('display', display, (name) => (name === 'lines' ? linesTexture : source));
      }

      telemetry.ticked = true;
      telemetry.seconds = frame.seconds;
      telemetry.videoFrame = settings.videoFrame;
      telemetry.settings = settings;
      telemetry.P = P;
      telemetry.N = N;
      telemetry.shown = shown;
      telemetry.workers = deck.failed ? 0 : deck.workers.length;
      const t = deck.times;
      telemetry.rate = t.length > 1 ? (1000 * (t.length - 1)) / (t[t.length - 1] - t[0]) : 0;
      telemetry.behind = shown ? Math.max(0, frame.seconds - shown.seconds) : 0;
      // A uniform name the shader does not have is a dead control (glUniform
      // on -1 is a no-op); the kit counts them.
      telemetry.missing = Object.entries(programs).flatMap(([name, p]) => [...p.missing].map((u) => `${name}.${u}`));

      if (hooks.afterRender) hooks.afterRender(gl, { shown, held, readFbo, W, H });
    },
  };
}

